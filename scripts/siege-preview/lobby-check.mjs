// Run a fresh compiled app on port 8094 with a temporary data directory first.
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const { chromium } = await import(process.env.QUIZZER_PLAYWRIGHT_MODULE || 'playwright');
const browser=await chromium.launch({executablePath:process.env.QUIZZER_CHROMIUM || undefined,headless:true,args:['--no-sandbox']});
const base='http://localhost:8094';
const out=new URL('../../output/siege-christmas-review/',import.meta.url).pathname;
await mkdir(out,{recursive:true});
const errors=[];
try {
  const context=await browser.newContext({viewport:{width:1600,height:1000}});
  const response=await context.request.post(base+'/api/quizzes',{data:{title:'Christmas Toybox Review',questions:[{type:'multiple_choice',text:'Which reindeer has a red nose?',options:['Rudolph','Comet'],correct:[0]}]}});
  assert.equal(response.status(),201);
  const quiz=await response.json();
  const host=await context.newPage();
  host.on('pageerror',e=>errors.push(e.message));
  host.on('response',r=>{if(r.status()>=400)errors.push(`${r.status()} ${r.url()}`);});
  await host.goto(base+'/host?quiz='+quiz.id);
  await host.getByLabel('Game mode').selectOption('siege');
  const selector=host.getByLabel('Kingdom Siege theme',{exact:true});
  await selector.waitFor();
  assert.equal(await selector.inputValue(),'christmas');
  await host.locator('.siege-board.siege-christmas img').first().waitFor({state:'visible'});
  await host.waitForLoadState('networkidle');
  const toy=await host.locator('.siege-board-img').getAttribute('src');
  await host.screenshot({path:out+'actual-lobby.png'});
  await selector.selectOption('classic');
  await host.waitForFunction(src=>document.querySelector('.siege-board-img')?.getAttribute('src')!==src,toy);
  await host.getByLabel('Kingdom Siege waves',{exact:true}).selectOption('10');
  assert.equal(await selector.inputValue(),'classic');
  await selector.selectOption('christmas');
  await host.reload();
  await selector.waitFor();
  assert.equal(await selector.inputValue(),'christmas');
  assert.equal(await host.getByLabel('Kingdom Siege waves',{exact:true}).inputValue(),'10');
  const phone=await context.newPage();
  await phone.setViewportSize({width:390,height:844});
  phone.on('pageerror',e=>errors.push(e.message));
  await phone.goto(base+'/');
  await phone.getByLabel('Your nickname').fill('Toy Captain');
  await phone.getByRole('button',{name:'Join',exact:true}).click();
  await host.getByRole('button',{name:'Start',exact:true}).click();
  await phone.locator('.siege-game.siege-christmas').waitFor();
  await phone.getByRole('button',{name:/Build/}).click();
  await phone.getByRole('dialog',{name:'Lane map'}).waitFor();
  await phone.getByRole('button',{name:'Lane 1 square 1',exact:true}).click();
  await host.locator('.defender').waitFor();
  await host.screenshot({path:out+'actual-game.png'});
  await host.reload();
  await host.locator('.siege-stage.siege-christmas').waitFor();
  host.on('dialog',d=>d.accept());
  await host.getByRole('button',{name:'End game',exact:true}).click();
  await host.getByRole('button',{name:/Play again/}).click();
  await selector.waitFor();
  assert.equal(await selector.inputValue(),'christmas');
  assert.equal(await host.getByLabel('Kingdom Siege waves',{exact:true}).inputValue(),'10');
  assert.deepEqual(errors,[]);
  console.log('PASS: compiled app, actual lobby defaults/theme/waves, reload, phone join and placement, host reconnect, Play again persistence, bundled artwork.');
} finally {await browser.close();}
