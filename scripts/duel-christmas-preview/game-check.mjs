import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const { chromium } = await import(process.env.QUIZZER_PLAYWRIGHT_MODULE || 'playwright');
const out = new URL('../../output/duel-christmas-review/', import.meta.url).pathname;
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.QUIZZER_CHROMIUM || undefined, headless: true, args: ['--no-sandbox'] });
try {
 const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
 const errors = [];
 page.on('pageerror', e => errors.push(e.message));
 page.on('response', r => { if (r.status() >= 400) errors.push(`${r.status()} ${r.url()}`); });
 await page.clock.install();
 const visit = async (url) => {
   await page.goto(`http://127.0.0.1:8102${url}`);
   await page.locator('.snowball-scene, .sd-town, .sd-street, .snowball-poster').first().waitFor();
   await page.evaluate(async () => { await Promise.all([...document.images].map(i => i.decode().catch(() => {}))); });
 };
 await visit('/?phase=open');
 assert.equal(await page.locator('.snowball-scene').count(), 4);
 assert.equal(await page.locator('.snowball-elf').count(), 9);
 assert.equal(new Set(await page.locator('.snowball-backdrop').evaluateAll(imgs => imgs.map(i => i.src))).size, 4);
 for (const world of await page.locator('.snowball-world').all()) {
   const box = await world.boundingBox();
   assert.ok(Math.abs(box.width / box.height - 16 / 9) < .02, 'body canvas keeps correct proportions');
 }
 await page.screenshot({ path: `${out}/host-four-arenas.png` });
 await visit('/?elapsed=1100');
 assert.equal(await page.locator('.snowball-projectile').count(), 4);
 assert.equal(await page.locator('.snowball-impact.hit').count(), 0);
 await page.screenshot({ path: `${out}/host-flight.png` });
 await visit('/?elapsed=1550');
 assert.equal(await page.locator('.snowball-projectile').count(), 0);
 assert.equal(await page.locator('.snowball-impact.hit').count(), 4);
 assert.equal(await page.locator('.snowball-elf[data-frame="7"]').count(), 4);
 await page.screenshot({ path: `${out}/host-impact.png` });
 await visit('/?elapsed=3200');
 assert.equal(await page.locator('.snowball-projectile, .snowball-impact').count(), 0, 'reconnecting after reveal does not replay effects');
 await visit('/?elapsed=6000');
 await page.clock.runFor(100);
 assert.equal(await page.locator('.duel-token').count(), 0, 'finished ladder movement does not replay on reconnect');
 await page.getByLabel('Draw', { exact: true }).check();
 await page.clock.runFor(1570);
 assert.equal(await page.locator('.snowball-impact.hit').count(), 0);
 assert.equal(await page.locator('.snowball-impact.miss').count(), 9);
 await page.screenshot({ path: `${out}/host-draw.png` });
 await page.getByLabel('Draw', { exact: true }).uncheck();
 await page.getByLabel('Reverse winner', { exact: true }).check();
 await page.clock.runFor(1570);
 assert.equal(await page.locator('.snowball-impact.hit').count(), 4);
 const fixture = await page.request.get('http://127.0.0.1:8102/fixture').then(r => r.json());
 const targets = await page.locator('.snowball-shot').evaluateAll(els => els.map(e => e.dataset.target));
 assert.deepEqual(targets, fixture.reveal.host.lastRound.arenas.map(a => a.duelists.find(d => d.outcome === 'win').id));
 await page.screenshot({ path: `${out}/host-reverse.png` });
 await visit('/?phase=podium');
 assert.equal(await page.locator('.snowball-poster').count(), 3);
 await page.screenshot({ path: `${out}/host-podium.png` });
 await visit('/?theme=classic&phase=open');
 assert.equal(await page.locator('.snowball-scene').count(), 0);
 assert.equal(await page.locator('.sd-street').count(), 4);
 await page.screenshot({ path: `${out}/host-classic.png` });
 await page.setViewportSize({ width: 390, height: 844 });
 await visit('/phone?phase=open');
 assert.equal(await page.locator('.snowball-backdrop').evaluate(img => img.naturalWidth), 800);
 await page.screenshot({ path: `${out}/phone-open.png` });
 await visit('/phone?elapsed=1550');
 assert.equal(await page.locator('.snowball-impact.hit').count(), 1);
 await page.screenshot({ path: `${out}/phone-impact.png` });
 await page.emulateMedia({ reducedMotion: 'reduce' });
 // Chromium dispatches the OS media-change event on its real task queue.
 await new Promise(resolve => setTimeout(resolve, 100));
 await page.clock.runFor(100);
 assert.equal(await page.locator('.snowball-elf[data-frame="7"]').count(), 0);
 await page.screenshot({ path: `${out}/phone-reduced-motion.png` });
 await visit('/phone?phase=podium');
 assert.equal(await page.locator('.snowball-poster').count(), 1);
 await page.screenshot({ path: `${out}/phone-podium.png` });
 assert.deepEqual(errors, []);
 console.log('PASS: four distinct arenas; nine avatars; release/impact; loser-only puffs; draws; reversed winners; reconnect; host/phone podium; classic fallback; phone art; reduced motion; no browser errors.');
} finally { await browser.close(); }
