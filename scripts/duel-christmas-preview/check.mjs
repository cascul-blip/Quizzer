import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const { chromium } = await import(process.env.QUIZZER_PLAYWRIGHT_MODULE || 'playwright');
const out = new URL('../../output/duel-christmas-prototype/', import.meta.url).pathname;
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.QUIZZER_CHROMIUM || undefined, headless: true, args: ['--no-sandbox'] });
try {
  const page = await browser.newPage({ viewport: { width: 1400, height: 1050 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => { if (r.status() >= 400) errors.push(`${r.status()} ${r.url()}`); });
  await page.clock.install();
  await page.goto('http://127.0.0.1:8101/');
  await page.evaluate(async () => { await Promise.all([...document.images].map(i => i.decode().catch(() => {}))); });
  await page.screenshot({ path: `${out}/ready.png` });
  await page.getByLabel('Timeline', { exact: true }).fill('800');
  assert.equal(await page.locator('.snowball').count(), 1);
  assert.equal(await page.locator('.impact').count(), 0, 'no puff before collision');
  await page.screenshot({ path: `${out}/flight.png` });
  await page.getByLabel('Timeline', { exact: true }).fill('1100');
  assert.equal(await page.locator('.snowball').count(), 0, 'ball disappears on collision');
  assert.equal(await page.locator('.impact').getAttribute('data-target'), 'right');
  assert.equal(await page.locator('.elf.right').getAttribute('data-frame'), '7');
  await page.screenshot({ path: `${out}/impact.png` });
  await page.getByLabel('Winner', { exact: true }).selectOption('right');
  await page.getByLabel('Timeline', { exact: true }).fill('1100');
  assert.equal(await page.locator('.impact').getAttribute('data-target'), 'left');
  assert.equal(await page.locator('.elf.left').getAttribute('data-frame'), '7');
  await page.screenshot({ path: `${out}/impact-left.png` });
  await page.getByRole('button', { name: 'Replay throw' }).click();
  await page.clock.runFor(850);
  assert.equal(await page.locator('.snowball').count(), 1);
  await page.clock.runFor(300);
  assert.equal(await page.locator('.impact').count(), 1);
  await page.clock.runFor(1000);
  assert.equal(await page.locator('.impact').count(), 0);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.clock.runFor(100);
  await page.getByLabel('Timeline', { exact: true }).fill('1100');
  assert.equal(await page.locator('.impact').count(), 1);
  assert.equal(await page.locator('.elf.left').getAttribute('data-frame'), '0');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: `${out}/phone.png` });
  assert.deepEqual(errors, []);
  console.log('PASS: ball flight, collision replaces ball with puff on loser, both directions, hit reaction, replay timing, reduced motion, phone rendering; no browser errors.');
} finally { await browser.close(); }
