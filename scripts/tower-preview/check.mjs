// Run the preview server first; Playwright and Chromium are required.
const { chromium } = await import(process.env.QUIZZER_PLAYWRIGHT_MODULE || 'playwright');
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const out = new URL('../../output/tower-christmas-review', import.meta.url).pathname;
await mkdir(out,{recursive:true});
const browser=await chromium.launch({executablePath: process.env.QUIZZER_CHROMIUM || undefined,headless:true,args:['--no-sandbox']});
const errors=[];
try {
 const page=await browser.newPage({viewport:{width:1600,height:900}});
 page.on('pageerror',e=>errors.push(e.message));
 page.on('response',r=>{if(r.status()>=400) errors.push(`${r.status()} ${r.url()}`)});
 await page.goto('http://127.0.0.1:8098/');
 await page.waitForTimeout(500);
 assert.equal(await page.locator('.tower-winter-backdrop').count(),1);
 assert.equal(await page.locator('.tree').count(),0);
 assert.equal(await page.locator('.skyline').count(),0);
 assert.equal(await page.locator('.tower-workshop-hoist').count(),3);
 assert.equal(await page.locator('.tower-bell-cell').count(),3);
 await page.screenshot({path:`${out}/host-three-teams.png`});
 await page.getByRole('button',{name:'Yeti attack'}).click();
 await page.waitForTimeout(1300);
 assert.equal(await page.locator('.tower-yeti').count(),1);
 await page.screenshot({path:`${out}/yeti-attack.png`});
 await page.waitForTimeout(2400);
 await page.getByLabel('Team count').selectOption('6');
 await page.waitForTimeout(150);
 await page.screenshot({path:`${out}/host-six-colors.png`});
 await page.getByLabel('Phase').selectOption('podium');
 assert.equal(await page.locator('.roof-flag').count(),6);
 await page.waitForTimeout(2500);
 await page.screenshot({path:`${out}/podium.png`});
 await page.getByLabel('Theme',{exact:true}).selectOption('classic');
 assert.equal(await page.locator('.tower-winter-backdrop').count(),0);
 assert.equal(await page.locator('.tree').count(),12);
 assert.equal(await page.locator('.skyline').count(),1);
 await page.screenshot({path:`${out}/normal-fallback.png`});
 await page.goto('http://127.0.0.1:8098/?height=30&teams=6');
 await page.setViewportSize({width:1024,height:768});
 await page.waitForTimeout(300);
 await page.screenshot({path:`${out}/host-tall-small-screen.png`});
 await page.setViewportSize({width:390,height:844});
 await page.goto('http://127.0.0.1:8098/phone?teams=6');
 await page.waitForTimeout(500);
 assert.equal(await page.locator('.tower-winter-backdrop').count(),1);
 assert.equal(await page.locator('.phone-skyline').count(),0);
 assert.ok((await page.locator('.build-area').boundingBox()).height>400, 'Phone build area must be visible');
 assert.ok(await page.locator('.build-svg .bb image').count()>0, 'Phone must draw tower tiles');
 assert.equal(await page.locator('.tower-bell-cell').count(),1);
 const urls=await page.locator('.bb image').evaluateAll(els=>els.map(e=>e.getAttribute('href')));
 assert.ok(urls.every(u=>u.includes('.webp')));
 await page.screenshot({path:`${out}/phone-red.png`});
 for(const [i,color] of ['Red','Blue','Yellow','Cyan','Purple','Pink'].entries()) {
  await page.getByLabel('Team color').selectOption(String(i));
  await page.waitForTimeout(80);
  await page.screenshot({path:`${out}/phone-${color.toLowerCase()}.png`});
 }
 await page.getByRole('button',{name:'Questions / build'}).click();
 assert.ok((await page.locator('.egg-chip').textContent()).includes('Yeti bell'));
 await page.screenshot({path:`${out}/phone-question.png`});
 await page.getByRole('button',{name:'Yeti attack'}).click();
 await page.waitForTimeout(100);
 assert.ok((await page.locator('.monster-flash').textContent()).includes('yeti'));
 await page.getByLabel('Theme',{exact:true}).selectOption('classic');
 await page.getByRole('button',{name:'Questions / build'}).click();
 await page.waitForTimeout(100);
 assert.equal(await page.locator('.tower-bell-cell').count(),0);
 assert.equal(await page.locator('.phone-skyline').count(),1);
 assert.equal(await page.locator('.tower-winter-backdrop').count(),0);
 await page.screenshot({path:`${out}/phone-normal.png`});
 assert.deepEqual(errors,[]);
 console.log('PASS: host, six colors, tall towers, podium, yeti attack, phone build/questions, normal fallback; no browser errors');
} finally {await browser.close();}
